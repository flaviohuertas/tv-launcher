import os, sys, glob, shutil, subprocess, zipfile, zlib

os.chdir(r"C:\TV")
os.makedirs("out/gen/io/freemytv", exist_ok=True)
os.makedirs("out/classes", exist_ok=True)

# Parse config.properties
props = {}
if os.path.exists("config.properties"):
    with open("config.properties", "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                props[k.strip()] = v.strip().strip('"').strip("'")

tmdb_key = props.get("tmdb_key", "")
watchmode_key = props.get("watchmode_key", "")
plex_url = props.get("plex_url", "")
plex_token = props.get("plex_token", "")
tmdb_region = props.get("tmdb_region", "BR")
latitude = props.get("latitude", "-19.9678")
longitude = props.get("longitude", "-44.1983")
city = props.get("city", "Betim")
language = props.get("language", "pt")
currency = props.get("currency", "BRL")
temperature = props.get("temperature", "C")
hide_services = props.get("hide_services", "")
hide_tabs = props.get("hide_tabs", "")
theme = props.get("theme", "auto")
disable_assistant = "true" if props.get("disable_assistant", "false").lower() == "true" else "false"
show_crypto = "true" if props.get("show_crypto", "true").lower() == "true" else "false"
hide_animation = "true" if props.get("hide_animation", "false").lower() == "true" else "false"
screensaver = "true" if props.get("screensaver", "true").lower() == "true" else "false"
generic = "false"

config_java = f"""package io.freemytv;

/** Generated by build_win.py from config.properties: edit that file, not this one. */
final class Config {{
    private Config() {{}}

    static final String TMDB_KEY = "{tmdb_key}";
    static final String WATCHMODE_KEY = "{watchmode_key}";
    static final String PLEX_URL = "{plex_url}";
    static final String PLEX_TOKEN = "{plex_token}";
    static final String TMDB_REGION = "{tmdb_region}";
    static final String LATITUDE = "{latitude}";
    static final String LONGITUDE = "{longitude}";
    static final String CITY = "{city}";
    static final String LANGUAGE = "{language}";
    static final String CURRENCY = "{currency}";
    static final String TEMPERATURE = "{temperature}";
    static final String HIDE_SERVICES = "{hide_services}";
    static final String HIDE_TABS = "{hide_tabs}";
    static final String THEME = "{theme}";
    static final boolean DISABLE_ASSISTANT = {disable_assistant};
    static final boolean SHOW_CRYPTO = {show_crypto};
    static final boolean HIDE_ANIMATION = {hide_animation};
    static final boolean SCREENSAVER = {screensaver};   // false: the TV keeps its own
    static final boolean GENERIC = {generic};   // built with --generic, as the APK on GitHub's releases (Updates)
}}
"""

with open("out/gen/io/freemytv/Config.java", "w", encoding="utf-8") as f:
    f.write(config_java)

tools_dir = os.path.abspath("tools-build")
jdk_bin = os.path.join(tools_dir, "jdk-17.0.12+7", "bin")
sdk_dir = os.path.join(tools_dir, "sdk")
build_tools = os.path.join(sdk_dir, "build-tools", "34.0.0")
android_jar = os.path.join(sdk_dir, "platforms", "android-34", "android.jar")
aapt2 = os.path.join(build_tools, "aapt2.exe")
zipalign = os.path.join(build_tools, "zipalign.exe")
d8_bat = os.path.join(build_tools, "d8.bat")
apksigner_bat = os.path.join(build_tools, "apksigner.bat")
javac = os.path.join(jdk_bin, "javac.exe")
keytool = os.path.join(jdk_bin, "keytool.exe")
core_lambda = os.path.join(build_tools, "core-lambda-stubs.jar")

print("1. Running aapt2 compile...")
subprocess.run([aapt2, "compile", "--dir", "app/res", "-o", "out/res.zip"], check=True)

print("2. Running aapt2 link...")
subprocess.run([
    aapt2, "link", "-o", "out/base.apk", "-I", android_jar,
    "--manifest", "app/AndroidManifest.xml", "--java", "out/gen", "out/res.zip",
    "--min-sdk-version", "26", "--target-sdk-version", "33", "-A", "app/assets", "-0", "ttf"
], check=True)

print("3. Fixing asset paths...")
tmp_apk = "out/base.apk.fixed"
renamed = 0
with zipfile.ZipFile("out/base.apk", "r") as zin:
    with zipfile.ZipFile(tmp_apk, "w") as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            name = item.filename.replace("\\", "/")
            if name != item.filename:
                renamed += 1
            zinfo = zipfile.ZipInfo(name)
            zinfo.compress_type = item.compress_type
            zinfo.date_time = item.date_time
            if item.compress_type == zipfile.ZIP_STORED:
                zinfo.CRC = zlib.crc32(data)
                zinfo.file_size = len(data)
            zout.writestr(zinfo, data)

if renamed > 0:
    os.replace(tmp_apk, "out/base.apk")
    print(f"Renamed {renamed} assets.")
else:
    if os.path.exists(tmp_apk): os.remove(tmp_apk)

print("4. Collecting java sources and compiling...")
java_sources = []
for root, _, files in os.walk("app/src"):
    for f in files:
        if f.endswith(".java"):
            java_sources.append(os.path.join(root, f))
for root, _, files in os.walk("out/gen"):
    for f in files:
        if f.endswith(".java"):
            java_sources.append(os.path.join(root, f))

bootcp = f"{android_jar};{core_lambda}"
cmd_javac = [
    javac, "-nowarn", "-Xlint:-options", "-source", "8", "-target", "8",
    "-bootclasspath", bootcp, "-classpath", android_jar,
    "-encoding", "UTF-8", "-d", "out/classes"
] + java_sources

subprocess.run(cmd_javac, check=True)

print("5. Running d8...")
class_files = []
for root, _, files in os.walk("out/classes"):
    for f in files:
        if f.endswith(".class"):
            class_files.append(os.path.join(root, f))

# d8.bat needs JAVA_HOME in env
env = os.environ.copy()
env["JAVA_HOME"] = os.path.join(tools_dir, "jdk-17.0.12+7")
env["PATH"] = jdk_bin + os.pathsep + env.get("PATH", "")

subprocess.run([
    d8_bat, "--release", "--min-api", "26", "--lib", android_jar, "--output", "out"
] + class_files, env=env, check=True)

print("6. Adding classes.dex to base.apk...")
with zipfile.ZipFile("out/base.apk", "a") as z:
    z.write("out/classes.dex", "classes.dex", compress_type=zipfile.ZIP_DEFLATED)

print("7. Running zipalign...")
if os.path.exists("out/aligned.apk"): os.remove("out/aligned.apk")
subprocess.run([zipalign, "-f", "-p", "4", "out/base.apk", "out/aligned.apk"], check=True)

print("8. Signing APK...")
if not os.path.exists("freemytv.keystore"):
    subprocess.run([
        keytool, "-genkeypair", "-keystore", "freemytv.keystore", "-alias", "freemytv",
        "-keyalg", "RSA", "-keysize", "2048", "-validity", "20000",
        "-storepass", "freemytv", "-keypass", "freemytv", "-dname", "CN=TV Launcher"
    ], check=True)

subprocess.run([
    apksigner_bat, "sign", "--ks", "freemytv.keystore", "--ks-pass", "pass:freemytv",
    "--key-pass", "pass:freemytv", "--out", "FreeMyTV.apk", "out/aligned.apk"
], env=env, check=True)

shutil.copyfile("FreeMyTV.apk", "TVLauncher.apk")
print("SUCCESS! Built FreeMyTV.apk and TVLauncher.apk successfully! Size:", os.path.getsize("TVLauncher.apk"))
